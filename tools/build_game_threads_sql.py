#!/usr/bin/env python3
"""Write supabase/RUN_ME_24_game_threads.sql from assets/games.js: one game_catalog row per game page (title + opening
post, facts only from the official schedule data), plus the get-or-create function the boards call on first visit.
Re-run after tools/build_gameday.py and apply the SQL again: the catalog upserts, nothing is deleted.
Usage: python3 tools/build_game_threads_sql.py"""
import json, os, re
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
s = open(os.path.join(ROOT, 'assets', 'games.js')).read()
G = json.loads(s[s.index('MP.GAMES=') + 9:].rstrip().rstrip(';'))
SPORT = {'football': 'football', 'mens-basketball': "men's basketball", 'womens-basketball': "women's basketball"}
MON = ['Jan.', 'Feb.', 'March', 'April', 'May', 'June', 'July', 'Aug.', 'Sept.', 'Oct.', 'Nov.', 'Dec.']
DOW = {'Mon': 'Monday', 'Tue': 'Tuesday', 'Wed': 'Wednesday', 'Thu': 'Thursday', 'Fri': 'Friday', 'Sat': 'Saturday', 'Sun': 'Sunday'}
def q(x): return "'" + x.replace("'", "''") + "'"
rows = []
for g in G['games']:
    y, m, d = map(int, g['d'].split('-'))
    vs = 'at' if g['ha'] == 'away' else 'vs.'
    title = f"Game thread: SMU {vs} {g['opp']}{' (exh.)' if g.get('ex') else ''} ({g['dow']}., {MON[m-1]} {d})"
    where = ', '.join(x for x in (g.get('venue'), g.get('city')) if x)
    bits = [f"Game thread for SMU {SPORT[g['sport']]} {vs} {g['opp']}{' (exhibition)' if g.get('ex') else ''}: {DOW.get(g['dow'], g['dow'])}, {MON[m-1]} {d}, {y}" + (f", {g['time']}" if g.get('time') else ', time TBA') + (f", {where.rstrip('.')}" if where else '') + '.',
            f"TV: {g['tv'] or 'TBA'}. Radio: {g['radio'] or 'TBA'}."]
    gc = (g.get('links') or {}).get('gamecenter')
    bits.append('The score box at the top of this thread shows the official final once SMU Athletics posts it. Keep it civil and follow the board rules.')
    if gc: bits.append(f"Live score and stats: {gc}")
    rows.append(f"  ({q(g['id'])}, {q(g['sport'])}, {q(title)}, {q(' '.join(bits))})")
sql = f"""-- RUN_ME_24_game_threads.sql  (generated by tools/build_game_threads_sql.py from assets/games.js, {G['checked']})
-- Live game threads. Adds threads.game_id, a public game_catalog (one row per game page) and game_thread(p_game), which
-- returns the game's thread and creates it (plus a staff opening post) the first time anyone opens it.
-- Deletes nothing: the catalog upserts, and the existing Syracuse game thread (id 2) is linked to its game, not replaced.
alter table public.threads add column if not exists game_id text;
create unique index if not exists threads_game_id_key on public.threads (game_id);

create table if not exists public.game_catalog (
  id text primary key, sport text not null, title text not null, opener text not null, updated_at timestamptz not null default now());
alter table public.game_catalog enable row level security;
drop policy if exists "game catalog is public" on public.game_catalog;
create policy "game catalog is public" on public.game_catalog for select to anon, authenticated using (true);
grant select on public.game_catalog to anon, authenticated;

insert into public.game_catalog (id, sport, title, opener) values
{',\n'.join(rows)}
on conflict (id) do update set sport = excluded.sport, title = excluded.title, opener = excluded.opener, updated_at = now();

update public.threads set game_id = 'fb-14454' where id = 2 and game_id is null and title ilike '%Syracuse%'
  and not exists (select 1 from public.threads where game_id = 'fb-14454');

create or replace function public.game_thread(p_game text) returns bigint
language plpgsql security definer set search_path = public as $$
declare tid bigint; c public.game_catalog%rowtype;
begin
  select id into tid from public.threads where game_id = p_game;
  if tid is not null then return tid; end if;
  select * into c from public.game_catalog where id = p_game;
  if not found then return null; end if;
  insert into public.threads (forum_id, sport, title, author_handle, game_id)
    values ('hilltop', c.sport, c.title, 'staff', p_game)
    on conflict (game_id) do nothing returning id into tid;
  if tid is null then select id into tid from public.threads where game_id = p_game; return tid; end if;
  insert into public.posts (thread_id, author_handle, body) values (tid, 'staff', c.opener);
  return tid;
end $$;
revoke all on function public.game_thread(text) from public;
grant execute on function public.game_thread(text) to anon, authenticated;
"""
out = os.path.join(ROOT, 'supabase', 'RUN_ME_24_game_threads.sql')
open(out, 'w').write(sql)
print('wrote', out, len(rows), 'games')
