-- SMU+ database schema for Supabase (Postgres 15+).
-- Run this once in Supabase: Dashboard > SQL Editor > New query > paste > Run. Then run seed.sql.
-- Safe to re-run: every object is created with IF NOT EXISTS / OR REPLACE, and policies are dropped first.
--
-- Security model (Row Level Security is ON for every table):
--   * Anyone (even signed out) can read forums, personas, content, threads, public posts and profile display names.
--   * Signed-in users can only create, change or delete their OWN rows.
--   * Posts in members-only boards are readable only by members (tier other than 'free').
--   * Membership tier changes are a DEMO switch for now (status = 'demo'). When real payments are added,
--     remove the memberships insert/update policies so only the server (service_role, e.g. a Stripe webhook) can change tiers.

create extension if not exists citext;

-- ---------- Profiles (one row per auth user, created by trigger) ----------
create table if not exists public.profiles (
  id           uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default 'Member' check (char_length(display_name) between 1 and 40),
  created_at   timestamptz not null default now()
);

-- ---------- Memberships (tier) ----------
create table if not exists public.memberships (
  user_id    uuid primary key references public.profiles(id) on delete cascade,
  tier       text not null default 'free' check (tier in ('free','mustang','pony','club')),
  status     text not null default 'demo' check (status in ('demo','active','canceled','past_due')),
  stripe_customer_id text,            -- reserved for a future Stripe TEST-mode integration (never set by the browser)
  updated_at timestamptz not null default now()
);

create or replace function public.is_member(uid uuid)
returns boolean language sql stable security definer set search_path = public as $$
  select exists(select 1 from public.memberships m where m.user_id = uid and m.tier <> 'free');
$$;

-- New auth user -> profile + free membership
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, display_name)
  values (new.id, left(coalesce(nullif(trim(new.raw_user_meta_data->>'display_name'), ''), split_part(new.email, '@', 1), 'Member'), 40))
  on conflict (id) do nothing;
  insert into public.memberships (user_id) values (new.id) on conflict (user_id) do nothing;
  return new;
end $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

-- ---------- Boards ----------
create table if not exists public.forums (
  id          text primary key,
  name        text not null,
  description text not null default '',
  premium     boolean not null default false,
  grp         text not null default 'Community',
  sort        int not null default 0
);

-- Fictional sample posters for the seeded threads (real users post as themselves via profiles)
create table if not exists public.personas (
  handle       text primary key,
  display_name text not null,
  tier_label   text not null default 'Member',
  since        text,
  post_count   text,
  staff        boolean not null default false
);

create table if not exists public.threads (
  id            bigint generated by default as identity primary key,
  forum_id      text not null references public.forums(id),
  sport         text,
  title         text not null check (char_length(title) between 3 and 140),
  author_id     uuid,
  author_handle text references public.personas(handle),
  pinned        boolean not null default false,
  hot           boolean not null default false,
  reply_count   int not null default 0,
  view_count    int not null default 0,
  created_at    timestamptz not null default now(),
  last_post_at  timestamptz not null default now(),
  constraint threads_author_id_fkey foreign key (author_id) references public.profiles(id) on delete set null,
  constraint threads_one_author check (author_id is not null or author_handle is not null)
);

create table if not exists public.posts (
  id            bigint generated by default as identity primary key,
  thread_id     bigint not null references public.threads(id) on delete cascade,
  author_id     uuid,
  author_handle text references public.personas(handle),
  body          text not null check (char_length(body) between 1 and 5000),
  quote_post_id bigint references public.posts(id) on delete set null,
  created_at    timestamptz not null default now(),
  constraint posts_author_id_fkey foreign key (author_id) references public.profiles(id) on delete set null,
  constraint posts_one_author check (author_id is not null or author_handle is not null)
);

create index if not exists threads_forum_last_idx on public.threads (forum_id, last_post_at desc);
create index if not exists threads_last_idx on public.threads (last_post_at desc);
create index if not exists threads_sport_idx on public.threads (sport);
create index if not exists threads_author_idx on public.threads (author_id);
create index if not exists posts_thread_created_idx on public.posts (thread_id, created_at);
create index if not exists posts_author_idx on public.posts (author_id);

create or replace function public.forum_is_premium(tid bigint)
returns boolean language sql stable security definer set search_path = public as $$
  select coalesce((select f.premium from public.threads t join public.forums f on f.id = t.forum_id where t.id = tid), false);
$$;

-- Keep reply counts and "last post" fresh
create or replace function public.on_post_insert()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  update public.threads
     set reply_count = reply_count + case when exists(select 1 from public.posts p where p.thread_id = new.thread_id and p.id <> new.id) then 1 else 0 end,
         last_post_at = new.created_at
   where id = new.thread_id;
  return new;
end $$;
drop trigger if exists posts_after_insert on public.posts;
create trigger posts_after_insert after insert on public.posts
  for each row execute function public.on_post_insert();

-- Create a thread and its first post in one call (used by the site)
create or replace function public.create_thread(p_forum text, p_sport text, p_title text, p_body text)
returns bigint language plpgsql security invoker set search_path = public as $$
declare tid bigint;
begin
  if auth.uid() is null then raise exception 'Sign in to start a thread' using errcode = '42501'; end if;
  insert into public.threads (forum_id, sport, title, author_id) values (p_forum, nullif(p_sport, ''), trim(p_title), auth.uid()) returning id into tid;
  insert into public.posts (thread_id, author_id, body) values (tid, auth.uid(), trim(p_body));
  return tid;
end $$;

-- View counter that anyone can bump without update rights on threads
create or replace function public.bump_thread_view(tid bigint)
returns void language sql security definer set search_path = public as $$
  update public.threads set view_count = view_count + 1 where id = tid;
$$;

-- ---------- Content library (seeded from the site's content data) ----------
create table if not exists public.content_items (
  id           text primary key,
  type         text not null check (type in ('video','article','podcast')),
  category     text not null,
  label        text,
  title        text not null,
  description  text,
  duration     text,
  members_only boolean not null default false,
  sport        text,
  sort         int not null default 0
);

-- ---------- Newsletter, progress, saved athletes ----------
create table if not exists public.newsletter_signups (
  id         bigint generated by default as identity primary key,
  email      citext not null unique check (email ~* '^[^@\s]+@[^@\s.]+(\.[^@\s.]+)*\.[a-z]{2,}$'),
  user_id    uuid references public.profiles(id) on delete set null,
  source     text not null default 'site',
  created_at timestamptz not null default now()
);

create table if not exists public.watch_progress (
  user_id    uuid not null references public.profiles(id) on delete cascade,
  item_id    text not null,
  progress   real not null default 0 check (progress between 0 and 1),
  updated_at timestamptz not null default now(),
  primary key (user_id, item_id)
);
create index if not exists watch_progress_recent_idx on public.watch_progress (user_id, updated_at desc);

create table if not exists public.saved_athletes (
  user_id    uuid not null references public.profiles(id) on delete cascade,
  athlete_id text not null,
  created_at timestamptz not null default now(),
  primary key (user_id, athlete_id)
);

-- ---------- Row Level Security ----------
alter table public.profiles           enable row level security;
alter table public.memberships        enable row level security;
alter table public.forums             enable row level security;
alter table public.personas           enable row level security;
alter table public.threads            enable row level security;
alter table public.posts              enable row level security;
alter table public.content_items      enable row level security;
alter table public.newsletter_signups enable row level security;
alter table public.watch_progress     enable row level security;
alter table public.saved_athletes     enable row level security;

do $$ declare r record; begin
  for r in select policyname, tablename from pg_policies where schemaname = 'public' and tablename in
    ('profiles','memberships','forums','personas','threads','posts','content_items','newsletter_signups','watch_progress','saved_athletes')
  loop execute format('drop policy if exists %I on public.%I', r.policyname, r.tablename); end loop;
end $$;

-- profiles: public names, edit your own
create policy "profiles are public"      on public.profiles for select using (true);
create policy "edit own profile"         on public.profiles for update using (auth.uid() = id) with check (auth.uid() = id);

-- memberships: see and (demo) change your own tier
create policy "read own membership"      on public.memberships for select using (auth.uid() = user_id);
create policy "demo: create own membership" on public.memberships for insert with check (auth.uid() = user_id and status = 'demo' and stripe_customer_id is null);
create policy "demo: change own tier"    on public.memberships for update using (auth.uid() = user_id) with check (auth.uid() = user_id and status = 'demo' and stripe_customer_id is null);

-- reference data: read-only for everyone
create policy "forums are public"        on public.forums        for select using (true);
create policy "personas are public"      on public.personas      for select using (true);
create policy "content is public"        on public.content_items for select using (true);

-- threads: everyone reads; signed-in users write their own (members only in premium boards)
create policy "threads are public"       on public.threads for select using (true);
create policy "start own thread"         on public.threads for insert with check (
  auth.uid() = author_id and author_handle is null and pinned = false and hot = false and reply_count = 0 and view_count = 0
  and (not (select premium from public.forums where id = forum_id) or public.is_member(auth.uid())));
create policy "edit own thread"          on public.threads for update using (auth.uid() = author_id) with check (auth.uid() = author_id and author_handle is null);
create policy "delete own thread"        on public.threads for delete using (auth.uid() = author_id);

-- posts: public boards readable by all; members-only boards readable by members
create policy "read posts"               on public.posts for select using (not public.forum_is_premium(thread_id) or public.is_member(auth.uid()));
create policy "write own post"           on public.posts for insert with check (
  auth.uid() = author_id and author_handle is null
  and (not public.forum_is_premium(thread_id) or public.is_member(auth.uid())));
create policy "edit own post"            on public.posts for update using (auth.uid() = author_id) with check (auth.uid() = author_id and author_handle is null);
create policy "delete own post"          on public.posts for delete using (auth.uid() = author_id);

-- newsletter: anyone can sign up; you can see only signups tied to your account
create policy "anyone can sign up"       on public.newsletter_signups for insert with check (user_id is null or user_id = auth.uid());
create policy "see own signup"           on public.newsletter_signups for select using (auth.uid() is not null and user_id = auth.uid());
create policy "remove own signup"        on public.newsletter_signups for delete using (auth.uid() is not null and user_id = auth.uid());

-- progress and saved athletes: private to each user
create policy "own progress"             on public.watch_progress for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "own saved athletes"       on public.saved_athletes for all using (auth.uid() = user_id) with check (auth.uid() = user_id);

-- Column-level limits: users may only edit the fields that make sense
revoke update on public.threads from anon, authenticated;
grant update (title, sport) on public.threads to authenticated;
revoke update on public.posts from anon, authenticated;
grant update (body) on public.posts to authenticated;
revoke update on public.memberships from anon, authenticated;
-- user_id is listed because supabase-js upsert sets every sent column; RLS still pins it to auth.uid().
grant update (user_id, tier, status, updated_at) on public.memberships to authenticated;
revoke update on public.profiles from anon, authenticated;
grant update (display_name) on public.profiles to authenticated;

-- Function permissions
revoke all on function public.handle_new_user() from public, anon, authenticated;
revoke all on function public.on_post_insert() from public, anon, authenticated;
grant execute on function public.is_member(uuid) to anon, authenticated;
grant execute on function public.forum_is_premium(bigint) to anon, authenticated;
grant execute on function public.create_thread(text, text, text, text) to authenticated;
grant execute on function public.bump_thread_view(bigint) to anon, authenticated;

-- ---------- Realtime: new posts appear live in open threads ----------
do $$ begin
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'posts') then
    alter publication supabase_realtime add table public.posts;
  end if;
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'threads') then
    alter publication supabase_realtime add table public.threads;
  end if;
end $$;
