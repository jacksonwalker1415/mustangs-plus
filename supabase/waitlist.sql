-- SMU+ waitlist (free, no payment). Safe to run more than once.
-- Run in Supabase: SQL Editor > New query > paste this whole file > Run.
-- Until this runs, the site saves waitlist signups in newsletter_signups with source 'waitlist' or 'waitlist:<affiliation>'.
-- The last statement copies those rows into the new table, so nothing is lost.

create extension if not exists citext;

create table if not exists public.waitlist (
  id              bigint generated by default as identity primary key,
  email           citext not null unique check (email ~* '^[^@\s]+@[^@\s.]+(\.[^@\s.]+)*\.[a-z]{2,}$'),
  name            text check (name is null or char_length(name) between 1 and 80),
  affiliation     text check (affiliation is null or affiliation in ('student','alum','fan','parent','other')),
  consent         boolean not null check (consent),          -- the form requires the privacy-notice box
  consent_version text not null default '2026-10-26' check (char_length(consent_version) <= 20),
  source          text not null default 'site' check (char_length(source) <= 40),
  created_at      timestamptz not null default now()
);

-- Row Level Security: visitors may add themselves; nobody but the project owner (service role / dashboard) can read, change or delete rows.
alter table public.waitlist enable row level security;
drop policy if exists "anyone can join the waitlist" on public.waitlist;
create policy "anyone can join the waitlist" on public.waitlist for insert to anon, authenticated with check (consent);

revoke all on public.waitlist from anon, authenticated;
grant insert (email, name, affiliation, consent, consent_version, source) on public.waitlist to anon, authenticated;

-- Move signups saved by the interim fallback into the waitlist.
insert into public.waitlist (email, affiliation, consent, consent_version, source, created_at)
select n.email,
       case when split_part(n.source, ':', 2) in ('student','alum','fan','parent','other') then split_part(n.source, ':', 2) end,
       true, '2026-10-26', 'newsletter-fallback', n.created_at
from public.newsletter_signups n
where n.source = 'waitlist' or n.source like 'waitlist:%'
on conflict (email) do nothing;
