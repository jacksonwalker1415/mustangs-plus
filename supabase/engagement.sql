-- ---------- Ledger ----------
create table if not exists public.point_events (
  id         bigint generated by default as identity primary key,
  user_id    uuid not null references public.profiles(id) on delete cascade,
  kind       text not null check (kind in ('checkin','early','streak','milestone','welcome','redeem','adjust')),
  points     int  not null check (points <> 0),
  ref        text not null,                    -- game id, milestone key or redemption id; (user, kind, ref) is unique
  game_id    text references public.engage_games(id),
  season     int  not null,
  note       text,
  created_at timestamptz not null default now(),
  constraint point_events_once unique (user_id, kind, ref)
);
create index if not exists point_events_user_idx   on public.point_events (user_id, created_at desc);
create index if not exists point_events_season_idx on public.point_events (season, user_id);
create index if not exists point_events_game_idx   on public.point_events (game_id) where game_id is not null;

create or replace function public.point_events_append_only()
returns trigger language plpgsql set search_path = public as $$
begin
  if tg_op = 'UPDATE' then raise exception 'point_events is append-only' using errcode = '42501'; end if;
  -- deletes are allowed only as part of deleting the account (the profile is already gone by then)
  if exists (select 1 from public.profiles where id = old.user_id) then
    raise exception 'point_events is append-only' using errcode = '42501';
  end if;
  return old;
end $$;
drop trigger if exists point_events_no_change on public.point_events;
create trigger point_events_no_change before update or delete on public.point_events
  for each row execute function public.point_events_append_only();

