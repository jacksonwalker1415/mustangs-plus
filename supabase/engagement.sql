-- ---------- RPC: check in at the gate ----------
create or replace function public.check_in(p_game_id text, p_code text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare uid uuid := auth.uid(); g record; mins int; w bigint := public.engage_window(now());
        att record; streak int; n int; pts int := 0; lines jsonb := '[]'::jsonb; got int; ms record;
begin
  if uid is null then return jsonb_build_object('ok', false, 'reason', 'signin', 'message', 'Sign in to check in.'); end if;
  if not exists (select 1 from public.profiles p where p.id = uid and p.is_student and p.smu_email_verified) then
    return jsonb_build_object('ok', false, 'reason', 'student', 'message', 'Verify your @smu.edu email to earn student points.');
  end if;
  select * into g from public.engage_games where id = p_game_id;
  if not found then return jsonb_build_object('ok', false, 'reason', 'game', 'message', 'That game isn''t open for check-in.'); end if;
  if exists (select 1 from public.checkins where user_id = uid and game_id = g.id) then
    return jsonb_build_object('ok', false, 'reason', 'already', 'message', 'You''re already checked in for this game.');
  end if;
  if g.kickoff is null or now() < g.kickoff - interval '2 hours' or now() > g.kickoff + interval '90 minutes' then
    return jsonb_build_object('ok', false, 'reason', 'closed', 'message', 'Check-in opens 2 hours before kickoff and closes 90 minutes after.', 'kickoff', g.kickoff);
  end if;
  select * into att from public.checkin_attempts where user_id = uid and game_id = g.id;
  if found and att.fails >= 8 and att.last_fail_at > now() - interval '10 minutes' then
    return jsonb_build_object('ok', false, 'reason', 'locked', 'message', 'Too many wrong codes. Try again in a few minutes or ask gate staff.');
  end if;
  -- accept the current code and the one before it (scan lag at the gate)
  if coalesce(regexp_replace(p_code, '\D', '', 'g'), '') not in (public.engage_code(g.id, w), public.engage_code(g.id, w - 1)) then
    insert into public.checkin_attempts as a (user_id, game_id, fails, last_fail_at) values (uid, g.id, 1, now())
      on conflict (user_id, game_id) do update set fails = case when a.last_fail_at < now() - interval '10 minutes' then 1 else a.fails + 1 end, last_fail_at = now();
    return jsonb_build_object('ok', false, 'reason', 'code', 'message', 'That code didn''t match. Codes change every 30 seconds, so scan the gate screen again.');
  end if;

  mins := floor(extract(epoch from (g.kickoff - now())) / 60)::int;
  streak := public.engage_prior_streak(uid, g.id);
  insert into public.checkins (user_id, game_id, minutes_before_kickoff, points) values (uid, g.id, mins, 0)
    on conflict do nothing;
  if not found then return jsonb_build_object('ok', false, 'reason', 'already', 'message', 'You''re already checked in for this game.'); end if;

  got := public.award(uid, 'checkin', 100, g.id, g.id, g.season, 'Checked in vs ' || g.opponent);
  pts := pts + got; lines := lines || jsonb_build_object('kind','checkin','label','Game-day check-in','points',got);
  if mins >= 45 then
    got := public.award(uid, 'early', 50, g.id, g.id, g.season, 'In the gates 45+ minutes early');
    pts := pts + got; lines := lines || jsonb_build_object('kind','early','label','Early arrival','points',got);
  end if;
  if streak >= 1 then
    got := public.award(uid, 'streak', least(100, 25 * streak), g.id, g.id, g.season, (streak + 1) || ' home games in a row');
    pts := pts + got; lines := lines || jsonb_build_object('kind','streak','label',(streak + 1) || '-game streak','points',got);
  end if;
  select count(*) into n from public.checkins c join public.engage_games eg on eg.id = c.game_id where c.user_id = uid and eg.season = g.season;
  for ms in select * from (values (3, 150, '3 home games'), (5, 250, '5 home games')) v(at, p, label) where v.at = n
            union all
            select (select count(*) from public.engage_games where season = g.season)::int, 500, 'Every home game'
             where n = (select count(*) from public.engage_games where season = g.season) loop
    got := public.award(uid, 'milestone', ms.p, 'season-' || g.season || '-' || ms.at, g.id, g.season, ms.label);
    pts := pts + got; if got > 0 then lines := lines || jsonb_build_object('kind','milestone','label',ms.label,'points',got); end if;
  end loop;
  update public.checkins set points = pts where user_id = uid and game_id = g.id;
  delete from public.checkin_attempts where user_id = uid and game_id = g.id;
  return jsonb_build_object('ok', true, 'game_id', g.id, 'opponent', g.opponent, 'minutes_before_kickoff', mins,
                            'streak', streak + 1, 'points', pts, 'lines', lines) || public.my_engagement();
end $$;

-- ---------- RPC: gate display (staff only) ----------
create or replace function public.gate_code(p_game_id text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare w bigint := public.engage_window(now());
begin
  if not exists (select 1 from public.gate_staff where user_id = auth.uid()) then
    raise exception 'Gate staff only' using errcode = '42501';
  end if;
  if not exists (select 1 from public.engage_games where id = p_game_id) then raise exception 'Unknown game'; end if;
  return jsonb_build_object('game_id', p_game_id, 'code', public.engage_code(p_game_id, w),
                            'expires_at', to_timestamp((w + 1) * 30));
end $$;

-- ---------- RPC: redeem ----------
create or replace function public.redeem_reward(p_reward_id text)
returns jsonb language plpgsql security definer set search_path = public, extensions as $$
declare uid uuid := auth.uid(); r record; bal int; mine int; rid bigint; c text;
begin
  if uid is null then return jsonb_build_object('ok', false, 'reason', 'signin', 'message', 'Sign in to redeem.'); end if;
  if not exists (select 1 from public.profiles p where p.id = uid and p.is_student and p.smu_email_verified) then
    return jsonb_build_object('ok', false, 'reason', 'student', 'message', 'Rewards are for verified SMU students.');
  end if;
  perform pg_advisory_xact_lock(hashtextextended('redeem:' || uid::text, 0));   -- one redemption at a time per student
  select * into r from public.rewards where id = p_reward_id and active;
  if not found then return jsonb_build_object('ok', false, 'reason', 'reward', 'message', 'That reward isn''t available.'); end if;
  select coalesce(sum(points), 0) into bal from public.point_events where user_id = uid;
  if bal < r.cost then
    return jsonb_build_object('ok', false, 'reason', 'balance', 'message', 'You need ' || (r.cost - bal) || ' more points for this.', 'balance', bal);
  end if;
  if r.per_user_limit is not null then
    select count(*) into mine from public.redemptions where user_id = uid and reward_id = r.id and status <> 'void';
    if mine >= r.per_user_limit then
      return jsonb_build_object('ok', false, 'reason', 'limit', 'message', 'You''ve already claimed this one.');
    end if;
  end if;
  update public.rewards set stock = stock - 1 where id = r.id and stock is not null and stock > 0;
  if r.stock is not null and not found then
    return jsonb_build_object('ok', false, 'reason', 'stock', 'message', 'That one''s all claimed for now.');
  end if;
  c := 'DEMO-' || upper(substr(encode(extensions.gen_random_bytes(3), 'hex'), 1, 4)) || '-' || upper(substr(encode(extensions.gen_random_bytes(3), 'hex'), 1, 4));
  insert into public.redemptions (user_id, reward_id, cost, code) values (uid, r.id, r.cost, c) returning id into rid;
  perform public.award(uid, 'redeem', -r.cost, 'redemption-' || rid, null, public.engage_season(), r.name);
  return jsonb_build_object('ok', true, 'code', c, 'reward_id', r.id, 'reward', r.name, 'cost', r.cost, 'balance', bal - r.cost);
end $$;

-- ---------- RPC: my summary ----------
create or replace function public.my_engagement()
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare uid uuid := auth.uid(); p record; b record; s int := public.engage_season(); streak int := 0; g record;
begin
  if uid is null then return jsonb_build_object('signed_in', false); end if;
  select is_student, smu_email_verified, class_year, show_on_leaderboard into p from public.profiles where id = uid;
  select coalesce(sum(points),0)::int as balance,
         coalesce(sum(points) filter (where points > 0 and season = s),0)::int as season_earned
    into b from public.point_events where user_id = uid;
  -- current streak: consecutive past home games attended, newest first
  for g in select id from public.engage_games where season = s and kickoff < now() - interval '90 minutes' order by kickoff desc loop
    exit when not exists (select 1 from public.checkins c where c.user_id = uid and c.game_id = g.id);
    streak := streak + 1;
  end loop;
  return jsonb_build_object('signed_in', true, 'is_student', coalesce(p.is_student,false), 'verified', coalesce(p.smu_email_verified,false),
    'class_year', p.class_year, 'show_on_leaderboard', coalesce(p.show_on_leaderboard,true),
    'balance', b.balance, 'season_earned', b.season_earned, 'tier', public.engage_tier(b.season_earned), 'streak', streak,
    'checkins', (select count(*) from public.checkins c join public.engage_games eg on eg.id = c.game_id where c.user_id = uid and eg.season = s));
end $$;

-- ---------- RPC: leaderboards (display names only) ----------
create or replace function public.leaderboard(p_scope text default 'season', p_game_id text default null, p_class_year int default null, p_limit int default 50)
returns table (rank int, display_name text, class_year int, points int, checkins int, is_me boolean)
language sql stable security definer set search_path = public as $$
  with tot as (
    select e.user_id, sum(e.points)::int as pts,
           count(distinct e.game_id) filter (where e.kind = 'checkin')::int as games,
           min(e.created_at) as first_at
      from public.point_events e
     where e.points > 0
       and case when p_scope = 'game' then e.game_id = p_game_id else e.season = public.engage_season() end
     group by e.user_id)
  select (row_number() over (order by t.pts desc, t.first_at))::int, p.display_name, p.class_year, t.pts, t.games, (t.user_id = auth.uid())
    from tot t join public.profiles p on p.id = t.user_id
   where p.is_student and p.smu_email_verified and p.show_on_leaderboard
     and (p_class_year is null or p.class_year = p_class_year)
   order by t.pts desc, t.first_at
   limit least(greatest(coalesce(p_limit, 50), 1), 100)
$$;

create or replace function public.class_standings()
returns table (class_year int, students int, points int, per_student int)
language sql stable security definer set search_path = public as $$
  select p.class_year, count(distinct p.id)::int, coalesce(sum(e.points), 0)::int,
         (coalesce(sum(e.points), 0) / greatest(count(distinct p.id), 1))::int
    from public.profiles p
    left join public.point_events e on e.user_id = p.id and e.points > 0 and e.season = public.engage_season()
   where p.is_student and p.smu_email_verified and p.class_year is not null
   group by p.class_year order by 3 desc
$$;

