-- ---------- Balances ----------
create or replace view public.point_balances with (security_invoker = true) as
  select user_id,
         coalesce(sum(points), 0)::int                                   as balance,
         coalesce(sum(points) filter (where points > 0), 0)::int        as earned,
         coalesce(-sum(points) filter (where points < 0), 0)::int       as spent
    from public.point_events group by user_id;

-- ---------- Rules ----------
create or replace function public.engage_season() returns int language sql stable as $$ select 2026 $$;

create or replace function public.engage_tier(p_earned int)
returns jsonb language sql immutable as $$
  select case
    when p_earned >= 1800 then jsonb_build_object('key','peruna','name','Peruna','floor',1800,'next',null,'next_name',null)
    when p_earned >= 1000 then jsonb_build_object('key','ford','name','Ford Stadium','floor',1000,'next',1800,'next_name','Peruna')
    when p_earned >=  400 then jsonb_build_object('key','dallashall','name','Dallas Hall','floor',400,'next',1000,'next_name','Ford Stadium')
    else                       jsonb_build_object('key','hilltop','name','Hilltop','floor',0,'next',400,'next_name','Dallas Hall') end
$$;

-- 6-digit code for a 30-second window. Same math as the demo in engage.js: HMAC-SHA256(secret, game_id:window), first 32 bits mod 1e6.
create or replace function public.engage_code(p_game text, p_window bigint)
returns text language sql stable security definer set search_path = public, extensions as $$
  select lpad(((('x' || substr(encode(extensions.hmac(convert_to(p_game || ':' || p_window, 'UTF8'), g.secret, 'sha256'), 'hex'), 1, 8))::bit(32)::bigint) % 1000000)::text, 6, '0')
    from public.engage_games g where g.id = p_game
$$;

create or replace function public.engage_window(p_at timestamptz default now())
returns bigint language sql stable as $$ select floor(extract(epoch from p_at) / 30)::bigint $$;

-- Consecutive home games checked in right before p_game (same season, by kickoff)
create or replace function public.engage_prior_streak(p_uid uuid, p_game text)
returns int language plpgsql stable security definer set search_path = public as $$
declare g record; n int := 0; this_ko timestamptz; this_season int;
begin
  select kickoff, season into this_ko, this_season from public.engage_games where id = p_game;
  for g in select id from public.engage_games where season = this_season and kickoff < this_ko order by kickoff desc loop
    exit when not exists (select 1 from public.checkins c where c.user_id = p_uid and c.game_id = g.id);
    n := n + 1;
  end loop;
  return n;
end $$;

create or replace function public.award(p_uid uuid, p_kind text, p_points int, p_ref text, p_game text, p_season int, p_note text)
returns int language plpgsql security definer set search_path = public as $$
begin
  insert into public.point_events (user_id, kind, points, ref, game_id, season, note)
  values (p_uid, p_kind, p_points, p_ref, p_game, p_season, p_note)
  on conflict on constraint point_events_once do nothing;
  return case when found then p_points else 0 end;
end $$;

-- ---------- RPC: student verification ----------
create or replace function public.verify_student(p_class_year int default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare uid uuid := auth.uid(); em text; confirmed boolean; bonus int := 0;
begin
  if uid is null then raise exception 'Sign in first' using errcode = '42501'; end if;
  select lower(u.email), (u.email_confirmed_at is not null) into em, confirmed from auth.users u where u.id = uid;
  if em is null or em !~ '^[^@\s]+@smu\.edu$' then
    return jsonb_build_object('ok', false, 'reason', 'not_smu', 'message', 'Use your @smu.edu email to verify as a student.');
  end if;
  if not confirmed then
    return jsonb_build_object('ok', false, 'reason', 'unconfirmed', 'message', 'Confirm your @smu.edu email from the link we sent, then try again.');
  end if;
  if p_class_year is not null and p_class_year not between 2026 and 2034 then
    return jsonb_build_object('ok', false, 'reason', 'class_year', 'message', 'Pick a class year between 2026 and 2034.');
  end if;
  update public.profiles
     set is_student = true, smu_email_verified = true,
         class_year = coalesce(p_class_year, class_year),
         student_verified_at = coalesce(student_verified_at, now())
   where id = uid;
  bonus := public.award(uid, 'welcome', 100, 'student', null, public.engage_season(), 'Verified SMU student');
  return jsonb_build_object('ok', true, 'bonus', bonus) || public.my_engagement();
end $$;

