-- SMU+ student engagement: points, game-day check-in, leaderboards, rewards and student accounts.
-- PROPOSED MIGRATION. Run it after schema.sql (and seed.sql) in the Supabase SQL Editor. Safe to re-run.
-- Points, check-ins and rewards are a DEMO for a class project: no real tickets, no cash value, nothing redeemable at SMU.
--
-- Security model
--   * Clients never write points, check-ins or redemptions directly. Every table here has RLS on, and anon/authenticated
--     have no INSERT/UPDATE/DELETE grants. All writes go through the SECURITY DEFINER functions below, which use auth.uid().
--   * point_events is an append-only ledger: rows can't be updated, and are deleted only when the account itself is deleted.
--   * Students read only their own ledger, check-ins and redemptions. Leaderboards expose display names, class year and totals only.
--   * Gate codes rotate every 30 seconds from a per-game secret that clients can't read. Only gate staff can fetch the live code.
--
-- Points rules (assets/engage.js mirrors these for demo mode; keep the two in sync)
--   check-in 100 · early arrival (45+ min before kickoff) +50 · streak +25 per consecutive home game before this one (max +100)
--   milestones: 3rd check-in +150, 5th +250, every home game +500 · verified student welcome +100
--   Check-in opens 2 hours before kickoff and closes 90 minutes after. TBD kickoffs stay closed.

