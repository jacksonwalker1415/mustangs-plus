-- SMU+ PROPOSED_12 (NOT RUN): "Report post" for The Mustang Board.
-- For the admin to review and run in the Supabase SQL Editor after schema.sql. Safe to re-run.
--
-- Who can do what:
--   * Signed-in members can file a report, as themselves only, once per post.
--   * Nobody can read reports through the site's API: no select policy, no select grant. That includes the reporter,
--     so a report can't be used to find out who else reported. Moderators read them in the Supabase dashboard
--     (service role), which bypasses RLS. If a mod role is added later, add a select policy for that role only.
--   * No updates or deletes from the site.
-- The site sends reports here only after REPORTS is set to true in assets/sb.js. Until then they stay in the browser.

create table if not exists public.post_reports (
  id          bigint generated by default as identity primary key,
  post_id     bigint not null references public.posts(id) on delete cascade,
  reporter_id uuid   not null default auth.uid() references public.profiles(id) on delete cascade,
  reason      text   not null check (reason in ('harassment','recruit_minor','doxxing','spam','other')),
  note        text   check (note is null or char_length(note) <= 500),
  created_at  timestamptz not null default now(),
  constraint post_reports_one_per_user unique (post_id, reporter_id)
);
create index if not exists post_reports_post_idx on public.post_reports (post_id);

alter table public.post_reports enable row level security;

drop policy if exists "members file their own reports" on public.post_reports;
create policy "members file their own reports" on public.post_reports
  for insert to authenticated
  with check (reporter_id = auth.uid());

-- Supabase grants everything on new tables to anon and authenticated by default. Take it back, then allow insert only.
revoke all on public.post_reports from anon, authenticated;
grant insert (post_id, reason, note) on public.post_reports to authenticated;
