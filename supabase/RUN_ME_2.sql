-- SMU+ RUN_ME_2 (D4): waitlist attribution + tier interest, cookie-free page_views counter, admin-only funnel.
-- Safe to run more than once. Additive only: nothing is removed. Works whether or not RUN_ME_2026-10-26.sql ran first.
-- Privacy: no IP, no user-agent string, no cookies, no fingerprinting. Session id is random, kept in sessionStorage.

create extension if not exists citext;

-- 1) Waitlist (same definition as supabase/waitlist.sql; skipped if it already exists)
create table if not exists public.waitlist (
  id              bigint generated by default as identity primary key,
  email           citext not null unique check (email ~* '^[^@\s]+@[^@\s.]+(\.[^@\s.]+)*\.[a-z]{2,}$'),
  name            text check (name is null or char_length(name) between 1 and 80),
  affiliation     text check (affiliation is null or affiliation in ('student','alum','fan','parent','other')),
  consent         boolean not null check (consent),
  consent_version text not null default '2026-10-26' check (char_length(consent_version) <= 20),
  source          text not null default 'site' check (char_length(source) <= 40),
  created_at      timestamptz not null default now()
);
alter table public.waitlist enable row level security;
do $$ begin
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'waitlist' and policyname = 'anyone can join the waitlist') then
    create policy "anyone can join the waitlist" on public.waitlist for insert to anon, authenticated with check (consent);
  end if;
end $$;

-- 1b) Attribution + tier interest on the waitlist
alter table public.waitlist add column if not exists utm_source    text check (utm_source    is null or char_length(utm_source)    <= 100);
alter table public.waitlist add column if not exists utm_medium    text check (utm_medium    is null or char_length(utm_medium)    <= 100);
alter table public.waitlist add column if not exists utm_campaign  text check (utm_campaign  is null or char_length(utm_campaign)  <= 100);
alter table public.waitlist add column if not exists utm_content   text check (utm_content   is null or char_length(utm_content)   <= 100);
alter table public.waitlist add column if not exists referrer_host text check (referrer_host is null or char_length(referrer_host) <= 200);
alter table public.waitlist add column if not exists tier_interest text check (tier_interest is null or tier_interest in ('free','mustang','all_access','red_blue','not_sure'));

revoke all on public.waitlist from anon, authenticated;
grant insert (email, name, affiliation, consent, consent_version, source,
              utm_source, utm_medium, utm_campaign, utm_content, referrer_host, tier_interest)
  on public.waitlist to anon, authenticated;

-- 2) Cookie-free visit counter
create table if not exists public.page_views (
  id            bigint generated by default as identity primary key,
  created_at    timestamptz not null default now(),
  path          text not null check (char_length(path) between 1 and 200),
  utm_source    text check (utm_source   is null or char_length(utm_source)   <= 100),
  utm_medium    text check (utm_medium   is null or char_length(utm_medium)   <= 100),
  utm_campaign  text check (utm_campaign is null or char_length(utm_campaign) <= 100),
  referrer_host text check (referrer_host is null or char_length(referrer_host) <= 200),
  session_id    text not null check (session_id ~ '^[A-Za-z0-9-]{8,64}$'),
  device        text not null check (device in ('mobile','desktop'))
);
create index if not exists page_views_created_at_idx on public.page_views (created_at);
alter table public.page_views enable row level security;
do $$ begin
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'page_views' and policyname = 'anyone can record a page view') then
    create policy "anyone can record a page view" on public.page_views for insert to anon, authenticated with check (true);
  end if;
end $$;
revoke all on public.page_views from anon, authenticated;
grant insert (path, utm_source, utm_medium, utm_campaign, referrer_host, session_id, device) on public.page_views to anon, authenticated;

-- 3) Funnel: visits, unique sessions and waitlist signups by day (America/Chicago) and utm_source.
--    Readable only from the dashboard / service role. Site visitors (anon) and signed-in users cannot read it.
create or replace view public.funnel_daily as
with v as (
  select (created_at at time zone 'America/Chicago')::date as day, coalesce(utm_source, '(direct)') as utm_source,
         count(*) as visits, count(distinct session_id) as sessions
  from public.page_views group by 1, 2
), w as (
  select (created_at at time zone 'America/Chicago')::date as day, coalesce(utm_source, '(direct)') as utm_source,
         count(*) as signups
  from public.waitlist group by 1, 2
)
select coalesce(v.day, w.day) as day, coalesce(v.utm_source, w.utm_source) as utm_source,
       coalesce(v.visits, 0) as visits, coalesce(v.sessions, 0) as sessions, coalesce(w.signups, 0) as signups
from v full join w on v.day = w.day and v.utm_source = w.utm_source;
revoke all on public.funnel_daily from public, anon, authenticated;
grant select on public.funnel_daily to service_role;
